RegisterNetEvent('__VICE_callback:client')
AddEventHandler('__VICE_callback:client',function(aJ,...)
    local aK=promise.new()
    TriggerEvent(string.format('c__VICE_callback:%s',aJ),function(...)
        aK:resolve({...})end,...)
    local aL=Citizen.Await(aK)
    TriggerServerEvent(string.format('__VICE_callback:server:%s:%s',aJ,...),table.unpack(aL))
end)
VICE.TriggerServerCallback=function(aJ,...)
    assert(type(aJ)=='string','Invalid Lua type at argument #1, expected string, got '..type(aJ))
    local aK=promise.new()
    local aM=GetGameTimer()
    RegisterNetEvent(string.format('__VICE_callback:client:%s:%s',aJ,aM))
    local aN=AddEventHandler(string.format('__VICE_callback:client:%s:%s',aJ,aM),function(...)
        aK:resolve({...})
    end)
    TriggerServerEvent('__VICE_callback:server',aJ,aM,...)
    local aL=Citizen.Await(aK)
    RemoveEventHandler(aN)
    return table.unpack(aL)
end
VICE.RegisterClientCallback=function(aJ,aO)
    assert(type(aJ)=='string','Invalid Lua type at argument #1, expected string, got '..type(aJ))
    assert(type(aO)=='function','Invalid Lua type at argument #2, expected function, got '..type(aO))
    AddEventHandler(string.format('c__VICE_callback:%s',aJ),function(aP,...)
        aP(aO(...))
    end)
end